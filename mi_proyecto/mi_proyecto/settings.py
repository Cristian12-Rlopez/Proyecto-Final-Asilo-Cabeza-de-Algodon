# --- Aiven (o cualquier MySQL en la nube): se activa si existe la variable DATABASE_URL ---------------
# Formato de Aiven: mysql://avnadmin:CLAVE@HOST:PUERTO/defaultdb?ssl-mode=REQUIRED
_database_url = os.environ.get('DATABASE_URL')
if _database_url:
    from urllib.parse import unquote, urlparse
    from django.core.exceptions import ImproperlyConfigured

    _u = urlparse(_database_url)
    DATABASES['default'].update({
        'NAME': _u.path.lstrip('/'),
        'USER': unquote(_u.username or ''),
        'PASSWORD': unquote(_u.password or ''),
        'HOST': _u.hostname,
        'PORT': str(_u.port or 3306),
    })
    # Aiven obliga a usar SSL: hace falta su certificado CA (carpeta certs/ o variable DB_SSL_CA)
    _ca = os.environ.get('DB_SSL_CA', str(BASE_DIR / 'certs' / 'aiven-ca.pem'))
    if not os.path.exists(_ca):
        raise ImproperlyConfigured(
            'Falta el certificado CA de Aiven. Descárgalo desde la consola de Aiven y guárdalo como '
            'certs/aiven-ca.pem (o apunta la variable DB_SSL_CA a su ruta).')
    DATABASES['default']['OPTIONS']['ssl'] = {'ca': _ca}

